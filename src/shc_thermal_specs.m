function specs = shc_thermal_specs
%SHC_THERMAL_SPECS Storage, convection and constant boundary definitions.
% Parameter columns: mask name, bilingual prompt, default expression.
% SPDX-License-Identifier: MIT
specs(1).name = 'Thermal mass';
specs(1).kind = 'mass';
specs(1).parameters = { ...
    'mass', 'Mass / 质量 [kg]', '1'; ...
    'cp', 'Specific heat / 比热容 [J/(kg K)]', '1000'; ...
    'Tinit', 'Initial temperature / 初始温度 [degC or K]', '20'};
specs(1).positive = {'mass','cp'};
specs(1).nonnegative = {};
specs(1).finite = {'Tinit'};
specs(1).extra = ['validateattributes(mass*cp,{''numeric''},' ...
    '{''real'',''scalar'',''finite'',''positive''},''SHC'',''thermal capacitance'');'];
specs(1).description = sprintf(['Constant thermal capacitance / 常热容节点.\n' ...
    'Input Qnet [W]: positive into this body. Output T [degC or K].\n' ...
    'dT/dt=Qnet/(mass*cp), T(0)=Tinit. Sum all incoming heat flows first.\n' ...
    'Uses a continuous Integrator: select a continuous solver (e.g. ode4 or ode45).\n' ...
    'No ambient loss or heat generation is included internally.']);

specs(2).name = 'Convection';
specs(2).kind = 'convection';
specs(2).parameters = { ...
    'h', 'Heat transfer coefficient / 对流换热系数 [W/(m^2 K)]', '10'; ...
    'area', 'Heat transfer area / 换热面积 [m^2]', '0.5'};
specs(2).positive = {'area'};
specs(2).nonnegative = {'h'};
specs(2).finite = {};
specs(2).extra = ['validateattributes(h*area,{''numeric''},' ...
    '{''real'',''scalar'',''finite'',''nonnegative''},''SHC'',''convective conductance'');'];
specs(2).description = sprintf(['Constant-coefficient convection / 常系数对流换热.\n' ...
    'Inputs T1,T2 [same temperature scale]; outputs Q1,Q2 [W].\n' ...
    'Q1=h*area*(T2-T1), Q2=-Q1. Positive heat enters the corresponding node.\n' ...
    'h=0 gives zero heat flow. This element has no thermal storage.\n' ...
    'It does not calculate fluid flow or infer h from flow conditions.']);

specs(3).name = 'Temperature boundary';
specs(3).kind = 'temperature';
specs(3).parameters = {'temperature', 'Prescribed temperature / 规定温度 [degC or K]', '20'};
specs(3).positive = {};
specs(3).nonnegative = {};
specs(3).finite = {'temperature'};
specs(3).extra = '';
specs(3).description = sprintf(['Constant prescribed temperature / 恒温边界.\n' ...
    'Output T is a scalar Simulink temperature signal. No heat-flow input.\n' ...
    'Connect to one side of a conduction/convection element.\n' ...
    'The boundary represents an ideal reservoir; its temperature is not integrated.\n' ...
    'A time-dependent boundary can instead use any compatible Simulink source.']);

specs(4).name = 'Heat flow boundary';
specs(4).kind = 'heatflow';
specs(4).parameters = {'power', 'Prescribed heat power / 规定热功率 [W]', '100'};
specs(4).positive = {};
specs(4).nonnegative = {};
specs(4).finite = {'power'};
specs(4).extra = '';
specs(4).description = sprintf(['Constant prescribed heat power / 恒热功率边界.\n' ...
    'Output Q [W]: positive adds heat; negative removes heat.\n' ...
    'Add this signal to the receiving thermal mass net heat input.\n' ...
    'This is total heat power, not area-specific heat flux [W/m^2].\n' ...
    'Use a standard Simulink source for a time-dependent heat-power signal.']);
end
