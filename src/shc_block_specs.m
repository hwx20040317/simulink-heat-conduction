function specs = shc_block_specs
%SHC_BLOCK_SPECS Editable definitions for all four conduction elements.
% Columns of parameters: variable name, dialog prompt, default expression.
% SPDX-License-Identifier: MIT
common = sprintf(['T1/T2: temperature [degC or K, use the same scale].\n' ...
    'Q1/Q2: heat entering node 1/node 2 [W].\n' ...
    'Q1=(T2-T1)/R; Q2=-Q1.\n' ...
    'This is a resistance element. Add external thermal capacitances for storage.']);

specs(1).name = 'Planar conduction';
specs(1).parameters = { ...
    'lambda', 'Thermal conductivity / 导热系数 [W/(m K)]', '10'; ...
    'distance', 'Distance between temperature nodes / 节点间距离 [m]', '0.01'; ...
    'area', 'Heat transfer area / 传热面积 [m^2]', '0.02'};
specs(1).resistance = 'distance/(lambda*area)';
specs(1).positive = {'lambda', 'distance', 'area'};
specs(1).nonnegative = {};
specs(1).geometry = '';
specs(1).description = sprintf('Single-material planar conduction.\nR=distance/(lambda*area).\n%s', common);
specs(1).icon = 'plane1';

specs(2).name = 'Planar conduction 2 materials';
specs(2).parameters = { ...
    'lambda1', 'Material 1 conductivity / 材料1导热系数 [W/(m K)]', '1'; ...
    'distance1', 'Node 1 to interface / 节点1到界面距离 [m]', '0.005'; ...
    'lambda2', 'Material 2 conductivity / 材料2导热系数 [W/(m K)]', '2'; ...
    'distance2', 'Interface to node 2 / 界面到节点2距离 [m]', '0.002'; ...
    'area', 'Heat transfer area / 传热面积 [m^2]', '0.01'; ...
    'ctr', 'Total contact resistance / 界面总热阻 [K/W]', '0.2'};
specs(2).resistance = 'distance1/(lambda1*area)+distance2/(lambda2*area)+ctr';
specs(2).positive = {'lambda1', 'lambda2', 'area'};
specs(2).nonnegative = {'distance1', 'distance2', 'ctr'};
specs(2).geometry = '';
specs(2).description = sprintf(['Two planar material layers in series, with optional contact resistance.\n' ...
    'R=distance1/(lambda1*area)+distance2/(lambda2*area)+ctr.\n' ...
    'ctr is TOTAL resistance [K/W], not area-specific resistance.\n%s'], common);
specs(2).icon = 'plane2';

specs(3).name = 'Radial conduction';
specs(3).parameters = { ...
    'lambda', 'Thermal conductivity / 导热系数 [W/(m K)]', '15'; ...
    'le', 'Axial length / 轴向长度 [m]', '0.1'; ...
    'diamInt', 'Inner temperature-node diameter / 内侧节点直径 [m]', '0.02'; ...
    'diamExt', 'Outer temperature-node diameter / 外侧节点直径 [m]', '0.04'};
specs(3).resistance = 'log(diamExt/diamInt)/(2*pi*lambda*le)';
specs(3).positive = {'lambda', 'le', 'diamInt', 'diamExt'};
specs(3).nonnegative = {};
specs(3).geometry = ['assert(diamExt>diamInt, ''SHC:InvalidGeometry'', ' ...
    '''Require 0 < diamInt < diamExt.'');'];
specs(3).description = sprintf(['One cylindrical shell, radial conduction. T1 is inside; T2 is outside.\n' ...
    'R=log(diamExt/diamInt)/(2*pi*lambda*le).\n' ...
    'The inner diameter must be positive.\n%s'], common);
specs(3).icon = 'radial1';

specs(4).name = 'Radial conduction 2 materials';
specs(4).parameters = { ...
    'lambda1', 'Inner material conductivity / 内层导热系数 [W/(m K)]', '15'; ...
    'lambda2', 'Outer material conductivity / 外层导热系数 [W/(m K)]', '0.2'; ...
    'le', 'Axial length / 轴向长度 [m]', '0.1'; ...
    'diamInt', 'Inner temperature-node diameter / 内侧节点直径 [m]', '0.02'; ...
    'diamCt', 'Material interface diameter / 材料界面直径 [m]', '0.024'; ...
    'diamExt', 'Outer temperature-node diameter / 外侧节点直径 [m]', '0.04'; ...
    'ctr', 'Total contact resistance / 界面总热阻 [K/W]', '0.05'};
specs(4).resistance = ['log(diamCt/diamInt)/(2*pi*lambda1*le)' ...
    '+log(diamExt/diamCt)/(2*pi*lambda2*le)+ctr'];
specs(4).positive = {'lambda1', 'lambda2', 'le', 'diamInt', 'diamCt', 'diamExt'};
specs(4).nonnegative = {'ctr'};
specs(4).geometry = ['assert(diamInt<diamCt && diamCt<diamExt, ''SHC:InvalidGeometry'', ' ...
    '''Require 0 < diamInt < diamCt < diamExt.'');'];
specs(4).description = sprintf(['Two coaxial cylindrical shells in series. T1 is inside; T2 is outside.\n' ...
    'R=log(diamCt/diamInt)/(2*pi*lambda1*le)' ...
    '+log(diamExt/diamCt)/(2*pi*lambda2*le)+ctr.\n' ...
    'ctr is TOTAL resistance [K/W], not area-specific resistance.\n%s'], common);
specs(4).icon = 'radial2';
end
